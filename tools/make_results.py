#!/usr/bin/env python3
"""Generate results/RESULTS.md (spec 18) from the outputs of the other make
targets. Every value is read from a file those targets wrote; nothing is
typed in by hand. A missing input is reported as "not run" with the command
that produces it.

Inputs:
  tb/out/regress_*.csv        make regress (and the parameter-variant run)
  formal/out/summary.csv      make formal
  perf/out/*.csv              make perf
  syn/out/summary.json        make syn
  syn/out/timing_paths_final_nocg.rpt
  tb/out/coverage.json        make cov
Also copies the plots into results/plots/.
"""
import csv, datetime, json, pathlib, re, shutil, subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "results"
NOT_RUN = "not run"


def rows(path):
    p = ROOT / path
    return list(csv.DictReader(open(p))) if p.exists() else None


def pct(x):
    return f"{100 * float(x):.1f}%"


def git_rev():
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True,
                              text=True).stdout.strip()
    except OSError:
        return "?"


def main():
    RES.mkdir(exist_ok=True)
    (RES / "plots").mkdir(exist_ok=True)
    for png in (ROOT / "perf" / "out").glob("*.png"):
        shutil.copy(png, RES / "plots" / png.name)

    out = ["# XDMA results", "",
           f"Generated by `make results` from commit `{git_rev()}` on "
           f"{datetime.date.today().isoformat()}. Every number below is read from the "
           "output of the command named next to it. Simulation: Verilator 5.054 + "
           "cocotb 2.1. Formal: SymbiYosys. Synthesis, timing and power: "
           "**Yosys + OpenSTA, ASAP7 (RVT, TT, NLDM), post-synthesis** (no place and "
           "route, ideal clock). See docs/ENV.md for versions.", ""]

    # ---------------------------------------------------------------- data
    lat = rows("perf/out/latency_tolerance.csv")
    burst = rows("perf/out/burst_length.csv")
    fair = rows("perf/out/fairness.csv")
    desc = rows("perf/out/desc_overhead.csv")
    xlat = rows("perf/out/translation.csv")
    formal = rows("formal/out/summary.csv")
    syn_p = ROOT / "syn/out/summary.json"
    syn = json.load(open(syn_p)) if syn_p.exists() else None
    cov_p = ROOT / "tb/out/coverage.json"
    cov = json.load(open(cov_p)) if cov_p.exists() else None
    reg = {}
    for p in sorted((ROOT / "tb/out").glob("regress_*.csv")):
        reg[p.stem.replace("regress_", "")] = list(csv.DictReader(open(p)))

    def lat_pt(l, fd, mo, mb=16):
        if not lat:
            return None
        for r in lat:
            if (int(r["latency"]), int(r["fifo_depth"]), int(r["max_out_ch"]), int(r["max_burst"])) == (l, fd, mo, mb):
                return r
        return None

    # ------------------------------------------------------- headline table
    out += ["## Summary (spec 18)", "", "| Metric | Value | Source |", "|---|---|---|",
            "| Channels / data width / max burst | 4 (2 MM2S + 2 S2MM) / 64-bit / 16 beats | parameters (rtl/xdma_top.sv) |",
            "| Outstanding transactions (engine-wide reads) | 16 (MAX_OUT_RD) | parameters |"]
    r50 = lat_pt(50, 64, 8)
    out.append(f"| Bandwidth utilization at latency 50, defaults | "
               f"{pct(r50['util_hw']) if r50 else NOT_RUN} | `make perf` (perf_latency, steady state, hardware counters) |")
    r200 = lat_pt(200, 128, 8)
    out.append(f"| Bandwidth utilization at latency 200, FIFO 128 | "
               f"{pct(r200['util_hw']) if r200 else NOT_RUN} | `make perf` |")
    lin = next((r for r in xlat or [] if r["mode"] == "linear"), None)
    out.append(f"| TLB hit rate, linear 64 KB transfer | "
               f"{pct(lin['hit_rate']) + ' (' + lin['tlb_hits'] + ' hits, ' + lin['tlb_misses'] + ' misses)' if lin else NOT_RUN} | `make perf` (perf_xlat) |")
    if syn:
        cg, nocg = syn["clock_gating"], syn["no_clock_gating"]
        out.append(f"| Achieved clock (Yosys + OpenSTA, ASAP7, post-synthesis) | "
                   f"{syn['fmax_ghz']:.2f} GHz ({syn['period_ps']} ps, WNS {nocg['wns_ps']:+.1f} ps) | `make syn` |")
        out.append(f"| Standard-cell area | {nocg['area_um2']:,.0f} µm² (clock gating off); "
                   f"{cg['area_um2']:,.0f} µm² (clock gating on) | `make syn` (Yosys stat, ASAP7 liberty) |")
        pa = nocg.get("power_active")
        pc = cg.get("power_active")
        if pa and pc:
            out.append(f"| Total power at target clock (perf_saturate activity) | "
                       f"{1e3 * pc['total_w']:.2f} mW with clock gating, {1e3 * pa['total_w']:.2f} mW without | `make syn` (OpenSTA, SAIF) |")
        else:
            out.append(f"| Total power at target clock | {NOT_RUN} | `make syn` |")
    else:
        out += [f"| Achieved clock | {NOT_RUN} | `make syn` |", f"| Standard-cell area | {NOT_RUN} | `make syn` |",
                f"| Total power at target clock | {NOT_RUN} | `make syn` |"]
    if reg:
        parts = []
        for tag, rs in reg.items():
            tests = sorted({r["test"] for r in rs})
            parts.append(f"{tag}: {sum(int(r['ok']) for r in rs)}/{len(rs)} runs pass "
                         f"({len(tests)} tests, up to {max(sum(1 for r in rs if r['test'] == t) for t in tests)} seeds each)")
        out.append(f"| Regression | {'; '.join(parts)} | `make regress SEEDS=N` |")
    else:
        out.append(f"| Regression | {NOT_RUN} | `make regress` |")
    if formal:
        prove = [r for r in formal if r["kind"] == "prove"]
        cover = [r for r in formal if r["kind"] == "cover"]
        out.append(f"| Formal | {sum(r['status'] == 'PASS' for r in prove)}/{len(prove)} proofs pass "
                   f"(unbounded); {sum(r['status'] == 'PASS' for r in cover)}/{len(cover)} cover sets reached; "
                   "w_mux proven at reduced size (2 writes in flight, 1-4 beat bursts), full size in simulation | `make formal` |")
    else:
        out.append(f"| Formal | {NOT_RUN} | `make formal` |")
    if cov:
        out.append(f"| Coverage | functional bins {cov['func_hit']}/{cov['func_total']} hit; "
                   f"line {cov.get('line', '?')}, toggle {cov.get('toggle', '?')}, "
                   f"assertion covers {cov.get('covers_hit', '?')}/{cov.get('covers_total', '?')} | `make cov` |")
    else:
        out.append(f"| Coverage | {NOT_RUN} | `make cov` |")
    out.append("")

    # --------------------------------------------------------- regression
    if reg:
        out += ["## Regression", "", "Command: `make regress SEEDS=N` (default parameters) and "
                "`python3 tb/regress.py --params FIFO_DEPTH=32,MAX_OUT_CH=4,MAX_BURST=8`. "
                "Every run has all assertions bound in; a run passes only with zero "
                "assertion failures.", ""]
        tests = sorted({r["test"] for rs in reg.values() for r in rs})
        tags = list(reg)
        out.append("| Test | " + " | ".join(tags) + " |")
        out.append("|---|" + "---|" * len(tags))
        for t in tests:
            cells = []
            for tag in tags:
                rs = [r for r in reg[tag] if r["test"] == t]
                cells.append(f"{sum(int(r['ok']) for r in rs)}/{len(rs)}" if rs else "-")
            out.append(f"| {t} | " + " | ".join(cells) + " |")
        out.append("")

    # ------------------------------------------------------------- formal
    if formal:
        out += ["## Formal (SymbiYosys)", "", "Command: `make formal`. `proven` = unbounded "
                "proof (k-induction or PDR); covers show each target's interesting "
                "behaviour is reachable, so no proof is vacuous.", "",
                "| Target | Task | Result | Time (s) |", "|---|---|---|---|"]
        notes = {"w_mux": " (reduced: 2 writes in flight, 1-4 beat bursts; full size covered by the same assertions in simulation)",
                 "addr_gen": " (LINE_BYTES 9 bits, LINES 4 bits; addresses and stride 32-bit)",
                 "fifo": "", "skid": "", "rr_arb": " (N = 4)"}
        for r in formal:
            out.append(f"| {r['target']} | {r['task']} | {r['result']}{notes.get(r['target'], '') if r['kind'] == 'prove' else ''} | {r['seconds']} |")
        out.append("")

    # --------------------------------------------------------- performance
    out += ["## Performance (spec 16)", "", "Command: `make perf`. Utilization = bytes / "
            "(8 B × cycles) in a steady-state window, from the BYTES and BUSY_CYC "
            "counters; every point is cross-checked against testbench timestamps "
            "(must agree within 1%). Memory model: fixed latency, no throttling.", ""]
    if lat:
        out += ["### Latency tolerance (one MM2S channel, sink always ready)", "",
                "![latency](plots/latency_fifo.png)", "", "![latency sweep](plots/latency_tolerance.png)", "",
                "| MAX_OUT_CH | FIFO (beats) | L=25 | L=50 | L=100 | L=200 |", "|---|---|---|---|---|---|"]
        for mo in (1, 2, 4, 8):
            for fd in (32, 64, 128):
                vals = [lat_pt(l, fd, mo) for l in (25, 50, 100, 200)]
                out.append(f"| {mo} | {fd} | " + " | ".join(pct(v["util_hw"]) if v else "-" for v in vals) + " |")
        worst = max(abs(float(r["util_hw"]) - float(r["util_tb"])) / max(float(r["util_tb"]), 1e-9) for r in lat)
        out += ["", f"Largest hardware-vs-testbench difference over all {len(lat)} points: {100 * worst:.3f}%.", ""]
        # Little's law check
        fits = []
        for r in lat:
            u = float(r["util_hw"])
            inflight = min(int(r["fifo_depth"]), 16 * int(r["max_out_ch"]))
            if u < 0.99:
                fits.append(inflight / u - int(r["latency"]))
        if fits:
            out += [f"Little's law: wherever utilization is below 100%, "
                    f"in_flight_beats / utilization - latency = {min(fits):.1f} .. {max(fits):.1f} cycles "
                    f"(mean {sum(fits) / len(fits):.1f}), i.e. utilization = in_flight / (latency + ~{sum(fits) / len(fits):.0f}) "
                    "with in_flight = min(FIFO_DEPTH, 16 × MAX_OUT_CH) beats. See docs/DESIGN_WALKTHROUGH.md section 2.", ""]
    if burst:
        out += ["### Burst length (latency 50, FIFO 64, MAX_OUT_CH 8)", "", "![burst](plots/burst_length.png)", "",
                "| MAX_BURST | Utilization |", "|---|---|"]
        out += [f"| {r['max_burst']} | {pct(r['util_hw'])} |" for r in burst]
        out.append("")
    if fair:
        out += ["### Fairness (all four channels saturating, latency 50)", "", "![fairness](plots/fairness.png)", "",
                "| Channel | Direction | Share of its direction | Share of all bytes |", "|---|---|---|---|"]
        out += [f"| {r['channel']} | {r['direction']} | {pct(r['share_in_direction'])} | {pct(r['share_total'])} |" for r in fair]
        out.append("")
    if desc:
        out += ["### Descriptor overhead (4 KB total, latency 50, end to end)", "", "![desc](plots/desc_overhead.png)", "",
                "| Shape | Prefetch | Utilization | Mean gap between descriptors (cycles) |", "|---|---|---|---|"]
        out += [f"| {r['shape']} | {'on' if r['prefetch'] == '1' else 'off'} | {pct(r['util_e2e'])} | "
                f"{float(r['mean_gap_cycles']):.0f} |" if r["mean_gap_cycles"] else
                f"| {r['shape']} | {'on' if r['prefetch'] == '1' else 'off'} | {pct(r['util_e2e'])} | - |" for r in desc]
        out += ["", "The gap with prefetch is the status-writeback round trip plus the first "
                "read latency (SPEC.md 7.1, DECISIONS.md D-045); prefetch removes the "
                "descriptor-fetch round trip.", ""]
    if xlat:
        out += ["### Translation cost (64 KB MM2S, latency 50, end to end)", "", "![xlat](plots/translation.png)", "",
                "| Mode | Utilization | TLB hits | TLB misses | Hit rate |", "|---|---|---|---|---|"]
        out += [f"| {r['mode']} | {pct(r['util_e2e'])} | {r['tlb_hits']} | {r['tlb_misses']} | "
                f"{pct(r['hit_rate']) if r['hit_rate'] else '-'} |" for r in xlat]
        out.append("")

    # ----------------------------------------------------------- synthesis
    if syn:
        nocg, cg = syn["no_clock_gating"], syn["clock_gating"]
        out += ["## Synthesis, timing and power (Yosys + OpenSTA, ASAP7, post-synthesis)", "",
                "Command: `make syn`. Yosys 0.71 (yosys-slang front end, hierarchy kept, ABC "
                "mapping with buffering and gate sizing) onto ASAP7 7.5-track RVT cells, "
                "typical corner, NLDM. OpenSTA with an ideal clock, I/O delays 20% of the "
                "period, BUFx2 input drive, 4 × BUFx2 output load. Clock sweep from 1000 ps "
                "in 50 ps steps, re-synthesizing at each period; the result is the fastest "
                "period with WNS >= 0.", "", "| Period (ps) | WNS (ps) | TNS (ps) |", "|---|---|---|"]
        out += [f"| {s['period_ps']} | {s['wns_ps']:+.1f} | {s['tns_ps']:.1f} |" for s in syn["sweep"]]
        out += ["", f"**Fmax: {syn['fmax_ghz']:.2f} GHz ({syn['period_ps']} ps).**", ""]
        out += ["### Area per block (clock gating off)", "", "| Block | Area (µm²) | Share |", "|---|---|---|"]
        tot = nocg["area_um2"]
        for k, v in sorted(nocg["area_by_block"].items(), key=lambda kv: -kv[1]):
            out.append(f"| {k} | {v:,.1f} | {100 * v / tot:.1f}% |")
        out += [f"| **total** | **{tot:,.1f}** | 100% |", "",
                f"FIFOs (all xdma_fifo instances: data FIFOs, burst queues, W-order queue): "
                f"{nocg['fifo_area_um2']:,.0f} µm² = {100 * nocg['fifo_share']:.1f}% of the total.", ""]
        out += ["### Power at the target clock", "", "| Activity | Clock gating | Internal (mW) | Switching (mW) | Leakage (mW) | Total (mW) |",
                "|---|---|---|---|---|---|"]
        for kind, label in (("active", "perf_saturate (all channels busy)"), ("idle", "idle")):
            for name, d in (("off", nocg), ("on", cg)):
                pw = d.get(f"power_{kind}")
                if pw:
                    out.append(f"| {label} | {name} | {1e3 * pw['internal_w']:.3f} | {1e3 * pw['switching_w']:.3f} | "
                               f"{1e3 * pw['leakage_w']:.4f} | {1e3 * pw['total_w']:.3f} |")
        act = nocg.get("activity_active")
        if act:
            out += ["", f"Activity: SAIF from RTL simulation (Verilator) of perf_saturate "
                    f"(32 KB per channel) and of 4000 idle cycles, instance names mapped to "
                    f"the netlist; {act.get('saif', 0):,} pins annotated from the SAIF, the rest "
                    f"({act.get('unannotated', 0):,}) propagated by OpenSTA. Power numbers are "
                    "therefore estimates; the clock-gating comparison uses the same activity "
                    "for both netlists."]
        out.append("")
        rpt = ROOT / "syn/out/timing_paths_final_nocg.rpt"
        if rpt.exists():
            txt = rpt.read_text()
            paths = re.findall(r"Startpoint: (\S+).*?Endpoint: (\S+).*?\n\s+(-?[0-9.]+)\s+slack", txt, re.S)
            out += ["### Top 10 timing paths at the final period", "", "| # | Startpoint | Endpoint | Slack (ps) |",
                    "|---|---|---|---|"]
            out += [f"| {i + 1} | `{a}` | `{b}` | {float(s):+.1f} |" for i, (a, b, s) in enumerate(paths[:10])]
            out += ["", "Full report: `syn/out/timing_paths_final_nocg.rpt` (after `make syn`). "
                    "Discussion: docs/DESIGN_WALKTHROUGH.md section 10.", ""]
    else:
        out += ["## Synthesis", "", f"{NOT_RUN}: `make syn`.", ""]

    # ------------------------------------------------------------ coverage
    if cov:
        out += ["## Coverage", "", "Command: `make cov`.", "", cov.get("markdown", ""), ""]
    else:
        out += ["## Coverage", "", f"{NOT_RUN}: `make cov` (step 9).", ""]

    (RES / "RESULTS.md").write_text("\n".join(out) + "\n")
    print(f"wrote {RES / 'RESULTS.md'}")

    # README: the summary table, between markers
    i = out.index("## Summary (spec 18)")
    j = out.index("", i + 2)
    table = "\n".join(out[i + 2:j])
    readme = ROOT / "README.md"
    txt = readme.read_text()
    a, b = "<!-- results:start -->", "<!-- results:end -->"
    if a in txt and b in txt:
        txt = txt[:txt.index(a) + len(a)] + "\n" + table + "\n\nGenerated by `make results`; details and sources in " \
              "[results/RESULTS.md](results/RESULTS.md).\n" + txt[txt.index(b):]
        readme.write_text(txt)
        print("updated README.md results table")


if __name__ == "__main__":
    main()
